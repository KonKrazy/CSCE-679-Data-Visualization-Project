"""Derive the correct answer for every study task from public/data/values.json.

Run: uv run python evaluation/answer_key.py  (writes evaluation/answer_key.md)
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / "public/data/values.json").read_text())
regions = json.loads((ROOT / "public/data/regions.geojson").read_text())
names = {f["properties"]["region_id"]: f["properties"]["region_name"] for f in regions["features"]}
labels = {i["key"]: i["label"] for i in data["indicators"]}
records = {(r["id"], r["y"]): r for r in data["records"]}


def country_rows(code, year):
    return [r for r in data["records"] if r["id"].startswith(f"{code}-") and r["y"] == year]


def z(row, key):
    return row["z"].get(key)


lines = ["# Answer key (generated by evaluation/answer_key.py — do not edit by hand)", ""]

# T1a: furthest behind on household wealth, Cambodia 2014.
rows = [r for r in country_rows("KHM", 2014) if z(r, "household_wealth") is not None]
t1a = min(rows, key=lambda r: z(r, "household_wealth"))
lines.append(f"- **T1a** {names[t1a['id']]} (z = {z(t1a, 'household_wealth'):+.2f})")

# T1b: Indonesia 2017, regions more than 1 SD behind on literacy.
behind = sorted(names[r["id"]] for r in country_rows("IDN", 2017) if (z(r, "literacy") or 0) < -1)
lines.append(f"- **T1b** {len(behind)} regions: {', '.join(behind)}")

# T2a: for the T1a region in 2014, the other indicator where it is furthest behind.
others = {k: v for k, v in t1a["z"].items() if k != "household_wealth" and v is not None}
worst = min(others, key=lambda k: others[k])
lines.append(f"- **T2a** {labels[worst]} (z = {others[worst]:+.2f})")

# T2b: Peru 2012, regions behind on electricity that are also behind on literacy.
elec = [r for r in country_rows("PER", 2012) if (z(r, "household_electricity") or 0) < 0]
both = [r for r in elec if (z(r, "literacy") or 0) < 0]
lines.append(f"- **T2b** {len(both)} of {len(elec)} regions behind on electricity are also behind on literacy")

# T3a: did the T1a region's wealth gap close or widen between 2000 and 2014?
start, end = (z(records[(t1a["id"], y)], "household_wealth") for y in (2000, 2014))
trend = "closing (moved toward the baseline)" if abs(end) < abs(start) else "widening (moved away from the baseline)"
lines.append(f"- **T3a** {trend}: z {start:+.2f} in 2000 → {end:+.2f} in 2014")

# T3b: Cambodia region whose wealth z rose most from 2000 to 2014.
gains = {
    rid: z(records[(rid, 2014)], "household_wealth") - z(records[(rid, 2000)], "household_wealth")
    for rid in {r["id"] for r in country_rows("KHM", 2014)}
    if (rid, 2000) in records
    and z(records[(rid, 2000)], "household_wealth") is not None
    and z(records[(rid, 2014)], "household_wealth") is not None
}
best = max(gains, key=lambda k: gains[k])
lines.append(f"- **T3b** {names[best]} (z change {gains[best]:+.2f})")

out = ROOT / "evaluation/answer_key.md"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(out.read_text())
