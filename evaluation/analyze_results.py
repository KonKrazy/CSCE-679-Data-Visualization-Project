"""Summarise filled-in study results into evaluation/results/summary.md.

Run: uv run python evaluation/analyze_results.py
Rows with an empty `correct` (tasks) or any empty answer (SUS) are ignored, so the
script can be run at any point while sessions are still being entered.
"""

import csv
import statistics
from pathlib import Path

RESULTS = Path(__file__).resolve().parent / "results"
TASKS = ["T1a", "T1b", "T2a", "T2b", "T3a", "T3b"]


def read(name):
    with open(RESULTS / name, newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def sus_score(row):
    answers = [int(row[f"q{i}"]) for i in range(1, 11)]
    return 2.5 * sum(a - 1 if i % 2 == 0 else 5 - a for i, a in enumerate(answers))


def fmt(values, fn, digits=1):
    return f"{fn(values):.{digits}f}" if values else "–"


tasks = [r for r in read("task_results.csv") if r["correct"].strip()]
sus = [r for r in read("sus_responses.csv") if all(r[f"q{i}"].strip() for i in range(1, 11))]

lines = ["# Study results summary (generated by analyze_results.py)", ""]
if not tasks and not sus:
    lines.append("No results entered yet. Fill in `task_results.csv` and `sus_responses.csv`.")
else:
    participants = sorted({r["participant"] for r in tasks} | {r["participant"] for r in sus})
    lines += [f"Participants with data: {len(participants)} ({', '.join(participants)})", "",
              "| Task | n | Accuracy | Median time (s) | Mean SEQ (1–7) | Gave up |",
              "|---|---|---|---|---|---|"]
    for task in TASKS:
        rows = [r for r in tasks if r["task"] == task]
        correct = [int(r["correct"]) for r in rows]
        times = [float(r["time_s"]) for r in rows if r["time_s"].strip()]
        seq = [int(r["seq"]) for r in rows if r["seq"].strip()]
        gave_up = sum(r["gave_up"].strip().lower() in {"1", "yes", "y", "true"} for r in rows)
        accuracy = f"{sum(correct)}/{len(correct)}" if correct else "–"
        lines.append(f"| {task} | {len(rows)} | {accuracy} | {fmt(times, statistics.median)} | "
                     f"{fmt(seq, statistics.mean)} | {gave_up} |")
    if sus:
        scores = [sus_score(r) for r in sus]
        spread = f", SD {statistics.stdev(scores):.1f}" if len(scores) > 1 else ""
        lines += ["", f"**SUS:** mean {statistics.mean(scores):.1f}{spread} "
                      f"(n = {len(scores)}; per participant: "
                      + ", ".join(f"{r['participant']} {s:.1f}" for r, s in zip(sus, scores)) + ")"]

out = RESULTS / "summary.md"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(out.read_text())
